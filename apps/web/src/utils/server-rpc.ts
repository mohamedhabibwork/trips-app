// Server-side RPC for the web app: every oRPC procedure the screens use is executed by a TanStack
// Start server function, never by a browser fetch to the API (SSR-ONLY, ARCHITECTURE §4.2).
//
// Tokens stay browser-only (§4.3): the server function receives the caller's bearer as input and
// replays R1–R3 around it — ensureFresh before the call, and on a refreshable 401 refresh once and
// replay exactly once. Errors cross the boundary as a plain envelope and are re-thrown client-side
// as `RpcCallError`, so `extractTransportError` (toasts, session-expired dialog) keeps working.
import type { ClientContext } from "@orpc/client";
import type { ProcedureUtils } from "@orpc/tanstack-query";
import type { UseMutationOptions, UseQueryOptions } from "@tanstack/react-query";
import { createServerFn } from "@tanstack/react-start";

import { authController } from "@/auth/instance";
import { RpcCallError, createRpcCall } from "@/auth/orpc-link";
import { needsRefreshOnError } from "@trips-app/auth";
import { ENV } from "@/env.public";

/** What the browser sends with each server-function call. */
interface RpcRequest {
  /** oRPC procedure path, e.g. `trips/getPublicTripDetail`. */
  procedure: string;
  input?: unknown;
  /** The caller's bearer, if it has one. The server never persists it. */
  accessToken?: string | null;
}

/** The call result: either the payload or a reconstructed transport failure. */
// eslint-disable-next-line @typescript-eslint/no-explicit-any -- the payload crosses the server-function
// boundary through the RPC serializer, which `unknown` fails to satisfy statically.
type RpcResult =
  | { ok: true; data: any }
  | { ok: false; status: number; code: string; message: string; data?: any };

const call = createServerFn({ method: "POST" })
  .validator((request: RpcRequest) => request)
  .handler(async ({ data }): Promise<RpcResult> => {
    const rpc = createRpcCall({
      baseUrl: ENV.VITE_SERVER_URL,
      getAccessToken: () => data.accessToken ?? null,
    });
    try {
      return { ok: true, data: await rpc(data.procedure, data.input) };
    } catch (error) {
      if (error instanceof RpcCallError) {
        return {
          ok: false,
          status: error.status,
          code: error.code,
          message: error.message,
          data: error.data,
        };
      }
      throw error;
    }
  });

/**
 * Runs one oRPC procedure on the server. Isomorphic: during SSR the server function executes
 * in-process; in the browser it is an RPC to this app's own server. R2 lives here: one refresh,
 * one replay, exactly like `buildAuthLink` used to do around the direct fetch.
 */
export async function serverRpc<T = unknown>(procedure: string, input?: unknown): Promise<T> {
  const send = () =>
    call({
      data: {
        procedure,
        input,
        accessToken: authController.accessToken(),
      },
    });

  await authController.ensureFresh();
  let result = await send();
  if (!result.ok) {
    const decision = needsRefreshOnError({
      status: result.status,
      code: result.code,
      procedure,
    });
    if (decision) {
      const refreshed = await authController.handleAuthError({
        status: result.status,
        code: result.code,
        procedure,
      });
      if (refreshed) result = await send();
    }
  }
  if (!result.ok) throw new RpcCallError(result.status, result.code, result.message, result.data);
  return result.data as T;
}

/**
 * `useQuery` options whose fetch runs on the server. The query key is generated by the oRPC
 * utils themselves, so it matches exactly what the route/screen loaders prefetch into the cache.
 *
 * ```ts
 * const query = useQuery(serverQueryOptions(orpc.trips.getPublicTripDetail, "trips/getPublicTripDetail", { input: { tripId } }));
 * ```
 */
export function serverQueryOptions<C extends ClientContext, I, O, E>(
  utils: ProcedureUtils<C, I, O, E>,
  procedure: string,
  options: { input: I } & Omit<UseQueryOptions<O, E>, "queryKey" | "queryFn">,
): {
  queryKey: ReturnType<ProcedureUtils<C, I, O, E>["queryKey"]>;
  queryFn: () => Promise<O>;
} & Omit<UseQueryOptions<O, E>, "queryKey" | "queryFn"> {
  const { input, ...rest } = options;
  return {
    queryKey: utils.queryKey({ input }),
    queryFn: () => serverRpc<O>(procedure, input),
    ...rest,
  };
}

/**
 * `useMutation` options whose mutation runs on the server. Callbacks (`onSuccess`, `onError`, …)
 * run in the browser as before — cache invalidation stays client-side.
 *
 * ```ts
 * const book = useMutation(serverMutationOptions(orpc.bookings.create, "bookings/create", {
 *   onSuccess: () => queryClient.invalidateQueries({ queryKey: orpc.bookings.key() }),
 * }));
 * ```
 */
export function serverMutationOptions<C extends ClientContext, I, O, E>(
  utils: ProcedureUtils<C, I, O, E>,
  procedure: string,
  options: Omit<UseMutationOptions<O, E, I>, "mutationFn"> = {},
): UseMutationOptions<O, E, I> {
  return {
    mutationKey: utils.mutationKey(),
    mutationFn: (input: I) => serverRpc<O>(procedure, input),
    ...options,
  };
}
