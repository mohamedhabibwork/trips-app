import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

import {
  createDb,
  DEMO_DEFAULT_PASSWORD,
  DEMO_MODERATOR_STAFF_CODE,
  DEMO_SHARED_TOTP_SECRET,
  DEMO_UNVERIFIED_OTP_CODE,
  demoAccountId,
  demoApplicationId,
  type DemoSeedSummary,
  seedDefaultData,
  seedDemoData,
} from "@trips-app/db";
import { createAdminService } from "@trips-app/service-admin";
import { computeTotpCode, createAuthService } from "@trips-app/service-auth";
import { createOnboardingService } from "@trips-app/service-onboarding";
import { createOrganizationService } from "@trips-app/service-organization";
import { beforeAll, describe, expect, test } from "bun:test";

function resolveTestDatabaseUrl(): string {
  if (process.env.DATABASE_URL) return process.env.DATABASE_URL;
  const envPath = resolve(import.meta.dir, "../../../apps/server/.env");
  if (existsSync(envPath)) {
    const content = readFileSync(envPath, "utf8");
    const match = content.match(/^DATABASE_URL=(.+)$/m);
    if (match?.[1]) return match[1].trim().replace(/^["']|["']$/g, "");
  }
  return "postgresql://postgres:postgres@localhost:5432/trips";
}

describe("Integration: Two-Tier Seeder, Auth, Roles, Settings & Onboarding", () => {
  const db = createDb({ DATABASE_URL: resolveTestDatabaseUrl() });
  const authService = createAuthService(db);
  const orgService = createOrganizationService(db);
  const adminService = createAdminService(db);
  const onboardingService = createOnboardingService(db);

  let seedPromise: Promise<DemoSeedSummary> | undefined;

  // Ids are generated by the seeder, so every test reads them from the seed summary instead of
  // hardcoding literals.
  function demoSeed(): Promise<DemoSeedSummary> {
    seedPromise ??= seedDemoData(db);
    return seedPromise;
  }

  beforeAll(async () => {
    await demoSeed();
  });

  test("1. Default & Demo Seeders populate roles, permissions, plans, settings, organizations, and accounts idempotently", async () => {
    const defaultResult = await seedDefaultData(db);
    expect(defaultResult.lookupTypesSeeded).toBe(23);
    expect(defaultResult.lookupsSeeded).toBeGreaterThanOrEqual(95);
    expect(defaultResult.rolesSeeded).toBe(10);
    expect(defaultResult.permissionsSeeded).toBe(9);
    expect(defaultResult.plansSeeded).toBe(12);
    expect(defaultResult.bootstrapSuperAdmin.email).toBe("admin@trips-enjoy.com");

    const demoResult = await seedDemoData(db);
    expect(demoResult.defaultSummary.lookupTypesSeeded).toBe(23);
    expect(demoResult.defaultSummary.lookupsSeeded).toBeGreaterThanOrEqual(95);
    expect(demoResult.organizationsSeeded).toBe(3);
    expect(demoResult.accountsSeeded).toBeGreaterThanOrEqual(25);
    expect(demoResult.applicationsSeeded).toBe(8);

    const roleCatalog = await authService.getRoleCatalog();
    expect(roleCatalog).toHaveLength(10);

    const permCatalog = await authService.getPermissionCatalog();
    expect(permCatalog.areas).toHaveLength(9);

    const orgPlans = await authService.getPlanCatalog({ role: "organization" });
    expect(orgPlans).toHaveLength(3);
  });

  test("2. Platform Admin Sign-In + TOTP Verification + First-Sign-In TOTP Enrollment (WF-ID-04)", async () => {
    // Enrolled Super Admin
    const step1 = await authService.adminSignIn({
      email: "superadmin@trips-enjoy.com",
      password: DEMO_DEFAULT_PASSWORD,
    });
    expect(step1.step).toBe("totp_verification_required");
    if (step1.step === "totp_verification_required") {
      const totpCode = computeTotpCode(DEMO_SHARED_TOTP_SECRET);
      const step2 = await authService.adminVerifyTotp({
        challengeToken: step1.challengeToken,
        totpCode,
      });
      expect(step2.step).toBe("authenticated");
      expect(step2.session.activeRole).toBe("admin");
      expect(step2.session.adminSubRole).toBe("super_admin");
    }

    // First-sign-in Operations Admin without enrolled TOTP (SCR-PUB-10)
    const enrollStep = await authService.adminSignIn({
      email: "new.admin@trips-enjoy.com",
      password: DEMO_DEFAULT_PASSWORD,
    });
    expect(enrollStep.step).toBe("totp_enrollment_required");
    if (enrollStep.step === "totp_enrollment_required") {
      expect(enrollStep.otpauthUri).toContain("otpauth://totp/");
      const code = computeTotpCode(enrollStep.secret);
      const enrolled = await authService.adminEnrollTotp({
        enrollmentToken: enrollStep.enrollmentToken,
        totpCode: code,
      });
      expect(enrolled.step).toBe("authenticated");
      expect(enrolled.session.adminSubRole).toBe("operations");
    }
  });

  test("3. Organization Owner & Multi-Org Employee Sign-In, 2FA, and Organization Switcher (WF-ID-05, WF-ID-07)", async () => {
    const seed = await demoSeed();
    const { nileHorizonEnterprise, redSeaGrowth } = seed.ids.organizations;

    const signInRes = await authService.staffSignIn({
      email: "multi.emp@trips-enjoy.com",
      password: DEMO_DEFAULT_PASSWORD,
    });
    expect(signInRes.step).toBe("staff_2fa_verification_required");

    if (signInRes.step === "staff_2fa_verification_required") {
      const code = computeTotpCode(DEMO_SHARED_TOTP_SECRET);
      const verified = await authService.staffVerifySecondFactor({
        challengeToken: signInRes.challengeToken,
        code,
        tenantId: nileHorizonEnterprise,
      });
      expect(verified.step).toBe("authenticated");
      expect(verified.session.activeTenantId).toBe(nileHorizonEnterprise);
      expect(verified.organizations.length).toBeGreaterThanOrEqual(2);

      // Switch active organization to Red Sea Explorers (Growth)
      const switched = await authService.switchOrganization(
        {
          accountId: demoAccountId(seed, "multi.emp@trips-enjoy.com"),
          sessionId: verified.session.sessionId,
        },
        {
          targetTenantId: redSeaGrowth,
        },
      );
      expect(switched.activeTenantId).toBe(redSeaGrowth);
      expect(switched.planTier).toBe("growth");
      expect(switched.permissions?.fleet).toBe("manage");
    }
  });

  test("4. Multi-Role Account Sign-In & Role Switcher (WF-ID-06, FR-AUTH-06)", async () => {
    const seed = await demoSeed();
    const login = await authService.signIn({
      identifier: "multirole@example.com",
      method: "password",
      password: DEMO_DEFAULT_PASSWORD,
      requestedRole: "traveler",
      surface: "web",
    });
    expect(login.step).toBe("authenticated");
    if (login.step === "authenticated") {
      expect(login.session.activeRole).toBe("traveler");

      const switched = await authService.switchRole(
        {
          accountId: demoAccountId(seed, "multirole@example.com"),
          sessionId: login.session.sessionId,
        },
        {
          targetRole: "platform_photographer",
        },
      );
      expect(switched.activeRole).toBe("platform_photographer");
      expect(switched.planTier).toBe("studio");
    }
  });

  test("5. Vehicle Moderator Sign-In with Staff Code & Single-Device Enforcement (SCR-PUB-19, D-107)", async () => {
    const modLogin = await authService.moderatorSignIn(
      {
        identifier: "+201000000061",
        staffCode: DEMO_MODERATOR_STAFF_CODE,
        surface: "mobile",
      },
      { deviceFingerprint: "mod-handheld-1" },
    );
    expect(modLogin.step).toBe("authenticated");
    expect(modLogin.session.activeRole).toBe("moderator");
    expect(modLogin.session.moderatorVehicleId).toBeDefined();
  });

  test("6. Special Auth Edge-Case Accounts: Unverified OTP, Locked, Suspended, and 30-Day Deletion Grace Auto-Restore", async () => {
    // Unverified account completes OTP verification with seeded code 123456
    const verifiedOtp = await authService.verifyOtp({
      targetIdentifier: "+201000000071",
      purpose: "registration",
      code: DEMO_UNVERIFIED_OTP_CODE,
      surface: "mobile",
    });
    expect(verifiedOtp.verified).toBe(true);
    expect(verifiedOtp.accountActivated).toBe(true);

    // Locked account throws RATE_LIMITED
    await expect(
      authService.signIn({
        identifier: "locked@example.com",
        method: "password",
        password: DEMO_DEFAULT_PASSWORD,
        surface: "web",
      }),
    ).rejects.toThrow(/locked/i);

    // Suspended account throws FORBIDDEN
    await expect(
      authService.signIn({
        identifier: "suspended@example.com",
        method: "password",
        password: DEMO_DEFAULT_PASSWORD,
        surface: "web",
      }),
    ).rejects.toThrow(/suspended/i);

    // Account in 30-day deletion grace period is automatically restored on sign-in (FR-AUTH-09, D-38)
    const restoredLogin = await authService.signIn({
      identifier: "deleting@example.com",
      method: "password",
      password: DEMO_DEFAULT_PASSWORD,
      surface: "web",
    });
    expect(restoredLogin.step).toBe("authenticated");
    if (restoredLogin.step === "authenticated") {
      expect(restoredLogin.autoRestoredFromDeletion).toBe(true);
    }
  });

  test("7. Organization Settings: Tenant Isolation (NOT_FOUND) & Plan-Gated Toggles (CON-06, FR-ORG-05)", async () => {
    const seed = await demoSeed();
    const { nileHorizonEnterprise, redSeaGrowth, sinaiStarter } = seed.ids.organizations;
    const nileOwnerId = demoAccountId(seed, "owner@nilehorizon.eg");
    const redSeaOwnerId = demoAccountId(seed, "owner@redsea.eg");
    const sinaiOwnerId = demoAccountId(seed, "owner@sinaitrails.eg");

    // Enterprise org can read its own settings
    const nileSettings = await orgService.getOrganizationSettings({
      accountId: nileOwnerId,
      activeRole: "organization_owner",
      activeTenantId: nileHorizonEnterprise,
    });
    expect(nileSettings.organization.planTier).toBe("enterprise");
    expect(nileSettings.settings.customBrandingEnabled).toBe(true);

    // Cross-tenant access returns NOT_FOUND (FR-ORG-01, IF-12)
    await expect(
      orgService.getOrganizationSettings(
        {
          accountId: nileOwnerId,
          activeRole: "organization_owner",
          activeTenantId: nileHorizonEnterprise,
        },
        { tenantId: sinaiStarter },
      ),
    ).rejects.toThrow(/not found/i);

    // Starter org cannot enable seatSelfSelectionEnabled (requires Growth+)
    await expect(
      orgService.updateOrganizationSettings(
        {
          accountId: sinaiOwnerId,
          activeRole: "organization_owner",
          activeTenantId: sinaiStarter,
        },
        { seatSelfSelectionEnabled: true },
      ),
    ).rejects.toThrow(/requires Growth or Enterprise plan/i);

    // Growth org CAN enable seatSelfSelectionEnabled, but CANNOT enable customBrandingEnabled
    const growthUpdated = await orgService.updateOrganizationSettings(
      {
        accountId: redSeaOwnerId,
        activeRole: "organization_owner",
        activeTenantId: redSeaGrowth,
      },
      { seatSelfSelectionEnabled: true },
    );
    expect(growthUpdated.seatSelfSelectionEnabled).toBe(true);

    await expect(
      orgService.updateOrganizationSettings(
        {
          accountId: redSeaOwnerId,
          activeRole: "organization_owner",
          activeTenantId: redSeaGrowth,
        },
        { customBrandingEnabled: true },
      ),
    ).rejects.toThrow(/requires Enterprise plan/i);
  });

  test("8. System Settings: Impact Preview (D-262) & Four-Eyes Approval Enforcement (D-233)", async () => {
    const seed = await demoSeed();
    const superAdminId = seed.defaultSummary.bootstrapSuperAdmin.id;
    const secondApproverId = demoAccountId(seed, "superadmin@trips-enjoy.com");

    const sys = await adminService.getSystemSettings();
    expect(sys.markets.EG.enabled).toBe(true);

    const preview = await adminService.previewSystemSettingsChange({
      marketCountryCode: "SA",
      marketEnabled: true,
    });
    expect(preview.requiresFourEyesApproval).toBe(true);
    expect(preview.affectedAccountsCount).toBeGreaterThan(0);

    // Updating a market without secondApproverAdminAccountId fails with PRECONDITION_FAILED
    await expect(
      adminService.updateSystemSettings(
        {
          accountId: superAdminId,
          activeRole: "admin",
          adminSubRole: "super_admin",
        },
        {
          marketCountryCode: "SA",
          marketEnabled: true,
          reason: "Enable Saudi Arabia market",
        },
      ),
    ).rejects.toThrow(/Four-eyes approval/i);

    // Succeeds when a distinct second admin approves
    const updatedSys = await adminService.updateSystemSettings(
      {
        accountId: superAdminId,
        activeRole: "admin",
        adminSubRole: "super_admin",
      },
      {
        marketCountryCode: "SA",
        marketEnabled: true,
        secondApproverAdminAccountId: secondApproverId,
        reason: "Enable Saudi Arabia market with four-eyes approval",
      },
    );
    expect(updatedSys.markets.SA.enabled).toBe(true);
  });

  test("9. Supplier Onboarding Queue: Overdue Filter, Changes Extension, Appeal & Org Supplier Onboarding", async () => {
    const seed = await demoSeed();
    const changesApplicantId = demoAccountId(seed, "applicant.changes@dahabtrips.eg");
    const changesApplicationId = demoApplicationId(seed, "applicant.changes@dahabtrips.eg");

    const overdueApps = await onboardingService.listReviewQueue({ overdueOnly: true });
    expect(overdueApps.length).toBeGreaterThanOrEqual(1);
    expect(overdueApps[0]?.isSlaOverdue).toBe(true);

    // Request one-time +7-day extension on Changes Requested application (FR-ONB-04)
    const extended = await onboardingService.requestChangesExtension(
      { accountId: changesApplicantId },
      { applicationId: changesApplicationId },
    );
    expect(extended.changesExtensionUsed).toBe(true);

    // Second extension request is rejected with CONFLICT
    await expect(
      onboardingService.requestChangesExtension(
        { accountId: changesApplicantId },
        { applicationId: changesApplicationId },
      ),
    ).rejects.toThrow(/already been used/i);

    // Approve Appealed photographer application (WF-APP-06)
    const appealApproved = await onboardingService.decideAppeal(
      {
        accountId: demoAccountId(seed, "ops.admin@trips-enjoy.com"),
        activeRole: "admin",
        adminSubRole: "operations",
      },
      {
        applicationId: demoApplicationId(seed, "applicant.appealed@alexandriaphoto.eg"),
        decision: "approve",
        decisionReasonCode: "appeal_portfolio_accepted",
        decisionNotes: "Outdoor excursion samples verified.",
      },
    );
    expect(appealApproved.state).toBe("Approved");

    // Organization-owned driver onboarding without admin queue (FR-ONB-09..10)
    const orgDriver = await onboardingService.onboardOrganizationSupplier(
      {
        accountId: demoAccountId(seed, "owner@nilehorizon.eg"),
        activeRole: "organization_owner",
        activeTenantId: seed.ids.organizations.nileHorizonEnterprise,
      },
      {
        supplierRole: "org_driver",
        fullName: "Hassan El-Masry (New Org Driver)",
        phone: "+201099887766",
        nationalId: "28901010105555",
        licenseNumber: "ORG-DRV-2026",
        licenseCategory: "First Degree Bus",
        labTestConsentSigned: true,
      },
    );
    expect(orgDriver.status).toBe("active");
    expect(orgDriver.owningTenantId).toBe(seed.ids.organizations.nileHorizonEnterprise);
  });
});
