/** Resolves to `true` only when `A` and `B` are mutually assignable, i.e. the same member set. */
type MutuallyAssignable<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false;

/**
 * Compile-time parity assertion between the `LookupTypeCode` union and the `LOOKUP_TYPE_CODES`
 * array (LK-22, design §11.10).
 *
 * Adding a code to one registry but not the other makes this type `false`, so the assignment below
 * fails `bun run check-types` naming this line. That is the whole point: the drift is caught at
 * build time, not in review.
 */
const lookupTypeCodeParity: MutuallyAssignable<
  LookupTypeCode,
  (typeof LOOKUP_TYPE_CODES)[number]
> = true;

