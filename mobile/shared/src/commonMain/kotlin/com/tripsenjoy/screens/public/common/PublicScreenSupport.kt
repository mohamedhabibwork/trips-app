// How a one-time code is delivered. Authenticator codes are generated by the app, so they need no phone number.
internal enum class PublicCodeMethod(val label: String) {
    Sms(label = "Text message"),
    App(label = "Authenticator app"),
}

// Choice between text message and authenticator app for a staff or moderator code.
@Composable
internal fun PublicCodeMethodChips(method: PublicCodeMethod, onSelect: (PublicCodeMethod) -> Unit) {
    val spacing = TripsEnjoyTheme.spacing
    Row(horizontalArrangement = Arrangement.spacedBy(spacing.space2)) {
        PublicCodeMethod.entries.forEach { option ->
            TeChip(label = option.label, selected = method == option, onClick = { onSelect(option) })
        }
    }
}
