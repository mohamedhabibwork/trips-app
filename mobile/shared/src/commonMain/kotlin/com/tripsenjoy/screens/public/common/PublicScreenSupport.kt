// Shared pieces for the public and auth screens. Forms are presentational: no network or auth calls.

// Length of every one-time code in the public flows (SHR-08).
internal const val PUBLIC_CODE_LENGTH = 6

// Minimum password length (NFR-SEC-02).
internal const val PUBLIC_PASSWORD_MIN_LENGTH = 12

// Page body: one scrolling column on the 16dp side gutter.
@Composable
internal fun PublicScreenColumn(content: @Composable ColumnScope.() -> Unit) {
    val spacing = TripsEnjoyTheme.spacing
    Column(
        modifier = Modifier
            .fillMaxSize()
            .verticalScroll(rememberScrollState())
            .padding(spacing.space4),
        verticalArrangement = Arrangement.spacedBy(spacing.space4),
        content = content,
    )
}

// Titled group of fields or copy inside a screen.
@Composable
internal fun PublicSection(title: String, content: @Composable ColumnScope.() -> Unit) {
    val spacing = TripsEnjoyTheme.spacing
    Column(verticalArrangement = Arrangement.spacedBy(spacing.space3)) {
        Text(text = title, style = TripsEnjoyTheme.typography.h3, color = TripsEnjoyTheme.colors.ink)
        content()
    }
}

// Helper or policy copy under a field or action.
@Composable
internal fun PublicNote(text: String) {
    Text(
        text = text,
        style = TripsEnjoyTheme.typography.caption,
        color = TripsEnjoyTheme.colors.inkMuted,
    )
}

